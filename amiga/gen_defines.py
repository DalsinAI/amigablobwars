#!/usr/bin/env python3
"""gen_defines.py defines.h defines.cpp: what upstream's tools/makedefs.sh
makes (the #define names and values of defines.h as two maps), in Python.
The AmiCradle Team. GPL 2 or later, like Blob Wars."""
import re
import sys

src, out = sys.argv[1], sys.argv[2]
pairs = []
for line in open(src, encoding="latin-1"):
    m = re.match(r".*#define ([A-Z][^ \t]*)[ \t]+(.*)", line.rstrip("\n"))
    if m:
        pairs.append((m.group(1), m.group(2)))
with open(out, "w") as f:
    f.write("// This is an autogenerated file, do not edit!\n\n#include \"headers.h\"\n\n")
    f.write("const std::map<const std::string, int> defines = {\n")
    for name, value in pairs:
        f.write(f'\t{{"{name}", {value}}},\n')
    f.write("};\n\nconst std::multimap<int, const std::string> reverseDefines = {\n")
    for name, value in pairs:
        f.write(f'\t{{{value}, "{name}"}},\n')
    f.write("};\n")
